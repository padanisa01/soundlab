package com.audiofx.app;

/**
 * Lookahead peak limiter for the live microphone capture path.
 *
 * Mirrors {@code audiofx/limiter.py} exactly (same defaults, same
 * algorithm): a delay line holds the audio back by {@link #LOOKAHEAD_MS}
 * while a peak envelope follower measures the <i>undelayed</i> input, so
 * gain reduction is fully engaged before a peak arrives. Zero overshoot
 * above the ceiling, by construction.
 *
 * Stereo is <i>linked</i>: one shared envelope/hold/gain across channels,
 * so the stereo image never shifts. The delay line is per channel.
 *
 * Attack (0.1 ms) is deliberately far under the lookahead (5 ms) so the
 * gain fully settles inside the lookahead window; release is 50 ms.
 * A detected peak is held for lookahead+1 iterations so the envelope
 * cannot decay before the peak's gain has been applied.
 *
 * True-peak mode (3-arg constructor, {@code truePeak=true}; DSP-3,
 * default off): the envelope follower runs on a 4x oversampled peak
 * stream instead of the raw sample peaks, so peaks that occur between
 * samples are caught too. Interpolation is a 32-tap polyphase
 * windowed-sinc FIR ({@link #TP_FIR_COEFFS}); the detected stream feeds
 * the follower 4 samples late (the interpolator's support reaches 4
 * samples ahead), still far inside the lookahead window. Delay
 * (5 ms), stereo linking, attack/hold/release are unchanged.
 *
 * Threading: create one instance per recording, use only on the capture
 * thread. {@link #processPcm16} reuses an internal scratch buffer, so it
 * never allocates on the audio thread after the first block.
 */
public final class LiveLimiter {

    private static final double CEILING_DB = -1.0;
    private static final double LOOKAHEAD_MS = 5.0;
    private static final double ATTACK_MS = 0.1;
    private static final double RELEASE_MS = 50.0;

    /** Oversampling factor of the true-peak detector (limiter.py: TRUE_PEAK_OVERSAMPLE). */
    static final int TRUE_PEAK_OVERSAMPLE = 4;

    /**
     * 32-tap polyphase windowed-sinc interpolation FIR for true-peak
     * detection. Generated by {@code limiter._tp_fir_coeffs()} in
     * audiofx/limiter.py -- the SAME numeric values; do not edit by
     * hand (a Python unit test diffs this table against the generator).
     * Taps that are mathematically zero (sinc at integer arguments)
     * are written as 0.0.
     */
    static final double[] TP_FIR_COEFFS = {
            0.0, -0.005394269095077871, -0.010733004038699265, -0.01131983727588515,
            0.0, 0.024406082142981584, 0.04871748881906059, 0.04734121107565832,
            0.0, -0.0847129417311841, -0.15856974657115114, -0.1488472760615212,
            0.0, 0.28420329890006324, 0.6271013006437518, 0.9037343471003871,
            1.0, 0.8858244329754273, 0.6035877486089342, 0.2684488373446078,
            0.0, -0.13439451236913652, -0.13993185622490914, -0.0728966597200525,
            0.0, 0.03823158844319808, 0.03801113135811911, 0.01837069650487362,
            0.0, -0.008163679266271689, -0.008183062595106079, -0.004831318968067989,
    };

    /** Samples the true-peak detector lags the input (its +4 support). */
    private static final int TP_DETECT_LAG = 4;
    /** Per-channel history kept for the interpolator (frames n-7..n). */
    private static final int TP_HISTORY = 8;

    private final double threshold = Math.pow(10.0, CEILING_DB / 20.0);
    private final int lookahead;
    private final double attackCoeff;
    private final double releaseCoeff;
    private final int holdSamples;
    private final int channels;

    private final float[][] delay;
    private int delayPos;
    private double peak;
    private int hold;
    private double gain = 1.0;
    private float[] scratch;

    private final boolean truePeak;
    /** True-peak interpolator history, per channel; null unless truePeak. */
    private final float[][] tpRing;
    /** Absolute index of the next frame fed to the true-peak detector. */
    private int tpFrame;

    public LiveLimiter(int sampleRate, int channels) {
        this(sampleRate, channels, false);
    }

    public LiveLimiter(int sampleRate, int channels, boolean truePeak) {
        this.channels = channels;
        this.truePeak = truePeak;
        lookahead = Math.max(1, (int) (LOOKAHEAD_MS * sampleRate / 1000.0));
        attackCoeff = Math.exp(-1.0 / (ATTACK_MS * sampleRate / 1000.0));
        releaseCoeff = Math.exp(-1.0 / (RELEASE_MS * sampleRate / 1000.0));
        holdSamples = lookahead + 1;
        delay = new float[channels][lookahead];
        delayPos = 0;
        tpRing = truePeak ? new float[channels][TP_HISTORY] : null;
        tpFrame = 0;
    }

    /** Sample with absolute index {@code idx} from the TP history (0 before the stream starts). */
    private float tpSample(int channel, int idx) {
        if (idx < 0) {
            return 0f;
        }
        return tpRing[channel][idx & (TP_HISTORY - 1)];
    }

    /**
     * True-peak estimate for frame {@code n} (max over channels and over
     * the 4x positions n, n+1/4, n+1/2, n+3/4). Only callable once frame
     * n+4 has entered the history, i.e. for n = current frame - lag.
     */
    private double tpDetectedPeak(int n) {
        double best = 0.0;
        for (int c = 0; c < channels; c++) {
            double chanBest = Math.abs(tpSample(c, n));
            for (int phase = 1; phase < TRUE_PEAK_OVERSAMPLE; phase++) {
                double frac = phase / (double) TRUE_PEAK_OVERSAMPLE;
                double y = 0.0;
                for (int j = -3; j <= 4; j++) {
                    int q = (int) Math.round((frac - j + 4.0) * TRUE_PEAK_OVERSAMPLE);
                    y += tpSample(c, n + j) * TP_FIR_COEFFS[q];
                }
                double ay = Math.abs(y);
                if (ay > chanBest) {
                    chanBest = ay;
                }
            }
            if (chanBest > best) {
                best = chanBest;
            }
        }
        return best;
    }

    /** Process interleaved float frames in place. */
    public void process(float[] io, int frames) {
        for (int f = 0; f < frames; f++) {
            int base = f * channels;
            double ax = 0.0;
            if (truePeak) {
                for (int c = 0; c < channels; c++) {
                    tpRing[c][tpFrame & (TP_HISTORY - 1)] = io[base + c];
                }
                if (tpFrame >= TP_DETECT_LAG) {
                    ax = tpDetectedPeak(tpFrame - TP_DETECT_LAG);
                }
                tpFrame++;
            } else {
                for (int c = 0; c < channels; c++) {
                    double a = Math.abs(io[base + c]);
                    if (a > ax) {
                        ax = a;
                    }
                }
            }
            if (ax >= peak) {
                peak = ax;
                hold = holdSamples;
            } else if (hold > 0) {
                hold--;
            } else {
                peak *= releaseCoeff;
            }
            double target = peak < 1e-12 ? 1.0 : Math.min(1.0, threshold / peak);
            double coeff = target < gain ? attackCoeff : releaseCoeff;
            gain += coeff * (target - gain);
            for (int c = 0; c < channels; c++) {
                float x = io[base + c];
                float[] dl = delay[c];
                float delayed = dl[delayPos];
                dl[delayPos] = x;
                io[base + c] = (float) (delayed * gain);
            }
            if (++delayPos == lookahead) {
                delayPos = 0;
            }
        }
    }

    /**
     * Limit a little-endian PCM-16 block in place. {@code nBytes} must be
     * a whole number of frames.
     */
    public void processPcm16(byte[] buf, int nBytes) {
        int frames = nBytes / (2 * channels);
        if (scratch == null || scratch.length < frames * channels) {
            scratch = new float[frames * channels];
        }
        for (int f = 0; f < frames; f++) {
            for (int c = 0; c < channels; c++) {
                int i = (f * channels + c) * 2;
                int s = (buf[i] & 0xff) | (buf[i + 1] << 8);
                scratch[f * channels + c] = s / 32768f;
            }
        }
        process(scratch, frames);
        for (int f = 0; f < frames; f++) {
            for (int c = 0; c < channels; c++) {
                float v = scratch[f * channels + c];
                if (v > 1f) {
                    v = 1f;
                } else if (v < -1f) {
                    v = -1f;
                }
                int s = Math.round(v * 32767f);
                int i = (f * channels + c) * 2;
                buf[i] = (byte) (s & 0xff);
                buf[i + 1] = (byte) ((s >> 8) & 0xff);
            }
        }
    }

    /** Clear delay line and state (call when starting a new take). */
    public void reset() {
        for (float[] dl : delay) {
            java.util.Arrays.fill(dl, 0f);
        }
        delayPos = 0;
        peak = 0.0;
        hold = 0;
        gain = 1.0;
        if (tpRing != null) {
            for (float[] ring : tpRing) {
                java.util.Arrays.fill(ring, 0f);
            }
            tpFrame = 0;
        }
    }
}
